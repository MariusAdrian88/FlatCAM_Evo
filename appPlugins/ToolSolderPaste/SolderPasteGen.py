"""Solder-paste paths, CNC tool settings and G-code headers from explicit data."""

from copy import deepcopy

from shapely import LineString

from appCommon.solderpaste import pad_paths, parameters, PREFIX
from appParsers.ParseGCode import safe_comment_text


def pad_geometry(poly, diameter, data, units, plan_parameters=None):
    """Return dispensing paths and calibrated volumes without changing the source pad."""
    if data.get(PREFIX + 'volume_mode', 'Legacy') != 'Legacy':
        if plan_parameters is None:
            plan_parameters = parameters(data, units, for_geometry=True)
        return pad_paths(poly, diameter, plan_parameters, units)

    # Margin is a percentage of the nozzle diameter.
    offset = ((data['tools_solderpaste_margin'] * diameter) * 0.01) + (diameter / 2)
    offseted_poly = poly.buffer(-offset)
    if offseted_poly.is_empty:
        return [], []

    # Follow the long axis even for rotated pads. Keep holes when clipping the path.
    corners = list(poly.minimum_rotated_rectangle.exterior.coords)
    dx = corners[1][0] - corners[0][0]
    dy = corners[1][1] - corners[0][1]
    if dx * dx + dy * dy < (corners[2][0] - corners[1][0]) ** 2 + \
            (corners[2][1] - corners[1][1]) ** 2:
        dx = corners[2][0] - corners[1][0]
        dy = corners[2][1] - corners[1][1]
    cx = (corners[0][0] + corners[2][0]) / 2
    cy = (corners[0][1] + corners[2][1]) / 2
    geo = LineString([(cx - dx / 2, cy - dy / 2),
                      (cx + dx / 2, cy + dy / 2)]).intersection(offseted_poly)
    if not geo.is_empty and geo.length > 0:
        return [geo], []
    return [], []


def cnc_tools(geometry_tools, current_tools):
    """Apply current machine settings while retaining planned geometry and quantities."""
    geometry_settings = {PREFIX + key for key in ('volume_mode', 'placement', 'thickness',
                                                 'volume', 'overlap', 'dot_dia', 'margin')}
    tools = {uid: deepcopy(tool) for uid, tool in geometry_tools.items() if tool['solid_geometry']}
    for uid, tool in tools.items():
        current = current_tools.get(uid)
        if current and current['tooldia'] == tool['tooldia']:
            tool['data'].update({key: value for key, value in current['data'].items()
                                 if key.startswith(PREFIX) and key not in geometry_settings})
    return tools


def gcode_header(version, version_date, name, object_type, units, time_str, preprocessor_name):
    """Build the shared preview/export header in the job's units and comment dialect."""
    gcode = '(G-CODE GENERATED BY FLATCAM v%s - www.flatcam.org - Version Date: %s)\n' % \
            (str(version), str(version_date)) + '\n'
    gcode += '(Name: ' + safe_comment_text(name) + ')\n'
    gcode += '(Type: ' + "G-code from " + str(object_type) + " for Solder Paste dispenser" + ')\n'
    gcode += '(Units: ' + units.upper() + ')\n' + "\n"
    gcode += '(Created on ' + time_str + ')\n' + '\n'
    if 'marlin' in (preprocessor_name or '').lower():
        gcode = gcode.replace('(', ';').replace(')', '')
    return gcode
