"""Probing G-code generation from explicit data, without application or UI state."""

from appParsers.ParseGCode import safe_comment_text


def generate_probing_gcode(coords, units, controller, travel, depth, feedrate,
                           coords_decimals, fr_decimals, name, version, version_date, time_str):
    """Build the controller's probe program, retracting before every XY move."""
    header = '(G-CODE GENERATED BY FLATCAM v%s - www.flatcam.org - Version Date: %s)\n' % \
             (str(version), str(version_date)) + '\n'
    header += '(This is a autolevelling probing GCode.)\n' \
              '(Make sure that before you start the job you first do a zero for all axis.)\n\n'
    header += '(Name: ' + safe_comment_text(name) + ')\n'
    header += '(Type: ' + "Autolevelling Probing GCode " + ')\n'
    header += '(Units: ' + units.upper() + ')\n'
    header += '(Created on ' + time_str + ')\n'

    if controller in ('MACH3', 'MACH4'):
        probing_command = 'G31'
        openfile_command = 'M40'
        closefile_command = 'M41'
    elif controller == 'LinuxCNC':
        probing_command = 'G38.2'
        openfile_command = '(PROBEOPEN a_probing_points_file.txt)'
        closefile_command = '(PROBECLOSE)'
    else:
        return

    p_gcode = header + '\n'
    if controller == 'LinuxCNC':
        p_gcode += "(The file with the stored probing points can be found)\n" \
                   "(in the configuration folder for LinuxCNC.)\n" \
                   "(The name of the file is: a_probing_points_file.txt.)\n"
    p_gcode += 'G21\n' if units == 'MM' else 'G20\n'
    p_gcode += 'G90\n'
    p_gcode += openfile_command + '\n'

    # Match App.dec_format's float conversion, including trailing .0 and signed zero.
    travel_text = str(float('%.*f' % (coords_decimals, float(travel))))
    depth_text = str(float('%.*f' % (coords_decimals, float(depth))))
    feedrate_text = str(float('%.*f' % (fr_decimals, float(feedrate))))
    p_gcode += 'G0 Z%s\n' % travel_text
    for x, y in coords:
        p_gcode += "G0 X%sY%s\n" % (
            str(float('%.*f' % (coords_decimals, float(x)))),
            str(float('%.*f' % (coords_decimals, float(y))))
        )
        p_gcode += "%s Z%s F%s\n" % (probing_command, depth_text, feedrate_text)
        p_gcode += 'G0 Z%s\n' % travel_text
    p_gcode += closefile_command + '\n'
    p_gcode += 'M2'
    return p_gcode
